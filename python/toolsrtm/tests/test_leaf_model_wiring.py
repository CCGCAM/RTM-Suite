    np.testing.assert_allclose(out.rdot, ref["rdot"].to_numpy(), rtol=1e-6, atol=1e-9)
    np.testing.assert_allclose(out.rsot, ref["rsot"].to_numpy(), rtol=1e-6, atol=1e-9)


