def test_foursail2_fluspect_b_matches_r_and_forces_2001():
    # Regression test for a real R bug found/fixed while building the AEO-Course
    # PROSAIL Shiny app's RTM tab: ToolsRTM::foursail2() never truncated `rsoil`
    # to Fluspect-B/-Cx's 2001-point domain (unlike foursail()'s equivalent
    # branches), so its internal SAIL2 core silently recycled a full-length
    # rsoil against 2001-long leaf optics. Python's foursail2() already forced
    # rsoil to 2001 via `force_2001` (see canopy.py), so this is confirming
    # the freshly-fixed R output now matches what Python always produced.
    ref = pd.read_csv(REFDATA / "ref_foursail2_fluspectb.csv")
    lut = {**FLUSPECT_B_LUT, "LIDFa": 45, "LIDFb": 0, "TypeLidf": 2, "LAI": 3, "hspot": 0.02,
           "tts": 30, "tto": 5, "psi": 0, "fraction_brown": 0.2, "diss": 0.5, "Cv": 1, "Zeta": 0}
    out = foursail2(lut, np.full(2101, 0.15), leaf_model="Fluspect-B")
    assert len(out.rdot) == 2001
    np.testing.assert_allclose(out.rdot, ref["rdot"].to_numpy(), rtol=1e-6, atol=1e-9)
    np.testing.assert_allclose(out.rsot, ref["rsot"].to_numpy(), rtol=1e-6, atol=1e-9)
    np.testing.assert_allclose(out.alfast, ref["alfast"].to_numpy(), rtol=1e-6, atol=1e-9)


_INFORM_COMMON = dict(LIDFa=55, LIDFb=0, TypeLidf=2, LAI=4, hspot=0.01, tts=30, tto=5, psi=0,
                       LAIu=0.5, sd=650, cd=4.5, h=20, skyl=0.1)


def test_inform_liberty_matches_r():
    ref = pd.read_csv(REFDATA / "ref_inform_liberty.csv")
    lut = dict(**LIBERTY_LUT, alpha=40, **_INFORM_COMMON)
    out = inform(lut, np.full(2101, 0.15), leaf_model="Liberty")
    assert len(out) == 2101
    np.testing.assert_allclose(out, ref["r_forest"].to_numpy(), rtol=1e-6, atol=1e-9)


